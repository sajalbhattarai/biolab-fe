#!/usr/bin/env bash
# generate-slurm-scripts.sh — writes the nine *.slurm job scripts (setup, containers, databases,
# annotate, annotate-classify, annotate-downstream, run-meta, gtdbtk-highmem, llm) to
# accessory-files/slurm/ from the SLURM settings in pipeline.conf.sh section 9.
# Run by setup.sh (or ./setup.sh --generate-slurm); the output is gitignored.
set -euo pipefail

_here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$_here/../../.." && pwd)"
SLURM_DIR="$REPO_ROOT/accessory-files/slurm"

# shellcheck source=../../../pipeline.conf.sh
source "$REPO_ROOT/pipeline.conf.sh"

# Without an allocation there is nothing valid to write (a computer without SLURM needs none).
if [[ -z "${SLURM_ACCOUNT:-}" ]]; then
    printf '[generate-slurm] SLURM_ACCOUNT is not set in pipeline.conf.sh section 9: no job scripts written\n'
    exit 0
fi

# Writes stdin to accessory-files/slurm/<name> and makes it executable.
_write() {
    local dest="$SLURM_DIR/$1"
    cat > "$dest"
    chmod +x "$dest"
    printf '[generate-slurm] wrote accessory-files/slurm/%s\n' "$1"
}

