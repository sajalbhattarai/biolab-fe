# ── 5. llm.slurm ─────────────────────────────────────────────────────────────
_write llm.slurm <<SLURM
#!/bin/bash
# GENERATED by generate-slurm-scripts.sh — do not edit by hand.
# To change settings, edit pipeline.conf.sh section 9, then run:
#   ./setup.sh --generate-slurm
#SBATCH --job-name=margie-llm-download
#SBATCH --account=${SLURM_ACCOUNT}
#SBATCH --partition=${SLURM_PARTITION}
#SBATCH --nodes=${SLURM_LLM_NODES}
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=${SLURM_LLM_CPUS}
#SBATCH --mem=${SLURM_LLM_MEM}
#SBATCH --time=${SLURM_LLM_TIME}
#SBATCH --output=logs/databases/llm/slurm-%j.out
#SBATCH --error=logs/databases/llm/slurm-%j.err

# llm.slurm — download LLM model weights into \$DB_ROOT/llm/base/
#             (large file, ~16 GB for Llama-3 8B; run as a dedicated job).
#
# BEFORE SUBMITTING — cache a HuggingFace token interactively on a login node:
#   ./setup.sh --databases-only --tool llm
#   # Enter your token at the prompt, then Ctrl+C to exit without downloading.
#   # Token is saved to processing/.hf-env/hf_token (chmod 600, local only).
#   # After the download finishes, revoke the token at:
#   #   https://huggingface.co/settings/tokens
#
# Also ensure LLM_BASE_MODEL is set in pipeline.conf.sh (section 6).
#
# Submit:
#   sbatch llm.slurm           (download configured model)
#   sbatch llm.slurm --redo    (delete existing weights and re-download)
set -euo pipefail

cd "\$SLURM_SUBMIT_DIR"
mkdir -p logs/databases/llm

# Fail fast if the token is missing — the token must already be cached.
# Fail fast here with a clear message rather than a silent skip.
_tok_file="processing/.hf-env/hf_token"
if [[ ! -s "\$_tok_file" ]]; then
    printf '[llm.slurm] ERROR: No HuggingFace token cached at %s\n' "\$_tok_file" >&2
    printf '[llm.slurm]        Cache a token interactively BEFORE submitting this job:\n' >&2
    printf '[llm.slurm]          ./setup.sh --databases-only --tool llm  (on a login node)\n' >&2
    printf '[llm.slurm]          # Enter token at prompt, then Ctrl+C to exit.\n' >&2
    exit 1
fi

module load apptainer 2>/dev/null || module load singularity 2>/dev/null || true

# Tell hf-env.sh not to wait for interactive input — job must fail clearly
# rather than hang if the token is missing or has been revoked.
export HF_NONINTERACTIVE=1

./setup.sh --databases-only --tool llm "\$@"
SLURM

