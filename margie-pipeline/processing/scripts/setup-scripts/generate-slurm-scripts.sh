#SBATCH --cpus-per-task=${SLURM_DOWNSTREAM_CPUS}
#SBATCH --mem=${SLURM_DOWNSTREAM_MEM}
#SBATCH --time=${SLURM_DOWNSTREAM_TIME}
#SBATCH --output=logs/annotation/downstream-%j.out
#SBATCH --error=logs/annotation/downstream-%j.err

# annotate-downstream.slurm — run annotation tool containers on existing gene calls.
# Skips gene calling; processes all genomes found in output/rasttk/.
# 6 tools run in parallel (PARALLEL_TOOLS); gram-agnostic tools finish, then
# the envelope stage infers each genome's envelope from tigrfam / pgap / pfam /
# uniprot, then the gram-dependent tools (psortb, deepsig, signalp4) start.
#
# Submit:               sbatch accessory-files/slurm/annotate-downstream.slurm
# Restrict to one tool: sbatch accessory-files/slurm/annotate-downstream.slurm --tool pfam
set -euo pipefail

cd "\$SLURM_SUBMIT_DIR"
mkdir -p logs/annotation

module load apptainer 2>/dev/null || module load singularity 2>/dev/null || true

export THREADS=\${SLURM_CPUS_PER_TASK:-${SLURM_DOWNSTREAM_CPUS}}

source ./pipeline.conf.sh

runner="./processing/scripts/run-individual-containers"

filter_tools=()
while [[ \$# -gt 0 ]]; do
    case "\$1" in
        --tool)   filter_tools+=("\$2"); shift 2 ;;
        --tool=*) filter_tools+=("\${1#--tool=}"); shift ;;
        *) echo "unknown option: \$1" >&2; exit 2 ;;
    esac
done

pre_tools=(kegg cog pfam pgap tigrfam dbcan eggnog merops tcdb uniprot interpro geneprop tmbed phobius operon)
post_tools=(psortb deepsig signalp4)
envelope_inputs=(tigrfam pgap pfam uniprot)

if (( \${#filter_tools[@]} )); then
    filtered_pre=()
    filtered_post=()
    for t in "\${pre_tools[@]}";  do [[ " \${filter_tools[*]} " == *" \$t "* ]] && filtered_pre+=("\$t");  done
    for t in "\${post_tools[@]}"; do [[ " \${filter_tools[*]} " == *" \$t "* ]] && filtered_post+=("\$t"); done
    pre_tools=("\${filtered_pre[@]+"\${filtered_pre[@]}"}")
    post_tools=("\${filtered_post[@]+"\${filtered_post[@]}"}")
    # the envelope stage reads these, so gram-dependent tools bring them along
    if (( \${#post_tools[@]} )); then
        for t in "\${envelope_inputs[@]}"; do
            [[ " \${pre_tools[*]} " == *" \$t "* ]] || pre_tools+=("\$t")
        done
    fi
fi

max_jobs=\${PARALLEL_TOOLS:-6}

_run_parallel() {
    local tools=("\$@")
    for tool in "\${tools[@]}"; do
        while (( \$(jobs -rp | wc -l) >= max_jobs )); do
            wait -n 2>/dev/null || sleep 0.1
        done
        echo "[annotate-downstream] starting: \$tool"
        "\$runner/run-\${tool}.sh" &
    done
    wait
    echo "[annotate-downstream] batch complete."
}

echo "[annotate-downstream] pre-tools  (\${#pre_tools[@]}):  \${pre_tools[*]:-none}"
echo "[annotate-downstream] post-tools (\${#post_tools[@]}): \${post_tools[*]:-none}"
echo "[annotate-downstream] max parallel: \$max_jobs   threads/tool: \${THREADS}"

(( \${#pre_tools[@]} ))  && _run_parallel "\${pre_tools[@]}"
if (( \${#post_tools[@]} )); then
    echo "[annotate-downstream] envelope inference"
    "\$runner/run-envelope.sh"
    _run_parallel "\${post_tools[@]}"
fi

echo "[annotate-downstream] all tools done."
SLURM

